package api

import (
	"bytes"
	"image"
	"image/color"
	"image/draw"
	"image/jpeg"

	"golang.org/x/image/font"
	"golang.org/x/image/font/basicfont"
	"golang.org/x/image/math/fixed"
)

// buildTestImage 生成一张 JPEG 测试页（不依赖 PDF 渲染组件）。
func buildTestImage(ver string) []byte {
	const W, H = 1240, 1754
	img := image.NewRGBA(image.Rect(0, 0, W, H))
	draw.Draw(img, img.Bounds(), image.NewUniform(color.White), image.Point{}, draw.Src)

	// 外边框
	drawBorder(img, 60, 60, W-60, H-60, color.Black, 4)

	// 标题与说明（像素字体放大）
	drawScaledText(img, "Print & Scan Test Page", 120, 200, 5, color.Black)
	drawScaledText(img, "If you can read this, printing works.", 120, 470, 2, color.Black)
	drawScaledText(img, "Generated by Print & Scan on UGREEN NAS.", 120, 560, 2, color.Black)
	drawScaledText(img, "Printer:", 120, 650, 2, color.Black)

	// 彩色测试条
	colors := []color.Color{
		color.RGBA{220, 40, 40, 255},
		color.RGBA{40, 160, 60, 255},
		color.RGBA{40, 80, 220, 255},
		color.Black,
	}
	x := 120
	for _, c := range colors {
		draw.Draw(img, image.Rect(x, 760, x+220, 980), image.NewUniform(c), image.Point{}, draw.Src)
		x += 250
	}

	// 灰阶条
	for i := 0; i < 8; i++ {
		g := uint8(255 - i*32)
		draw.Draw(img, image.Rect(120+i*130, 1060, 120+i*130+120, 1220), image.NewUniform(color.RGBA{g, g, g, 255}), image.Point{}, draw.Src)
	}

	drawScaledText(img, "Color / grayscale / alignment check", 120, 1320, 2, color.Black)
	drawScaledText(img, "Version "+ver, 120, 1420, 2, color.Gray{Y: 90})

	var buf bytes.Buffer
	_ = jpeg.Encode(&buf, img, &jpeg.Options{Quality: 92})
	return buf.Bytes()
}

func drawBorder(img *image.RGBA, x0, y0, x1, y1 int, c color.Color, w int) {
	draw.Draw(img, image.Rect(x0, y0, x1, y0+w), image.NewUniform(c), image.Point{}, draw.Src)
	draw.Draw(img, image.Rect(x0, y1-w, x1, y1), image.NewUniform(c), image.Point{}, draw.Src)
	draw.Draw(img, image.Rect(x0, y0, x0+w, y1), image.NewUniform(c), image.Point{}, draw.Src)
	draw.Draw(img, image.Rect(x1-w, y0, x1, y1), image.NewUniform(c), image.Point{}, draw.Src)
}

// drawScaledText 用 7x13 像素字体绘制并放大，实现大字号。
func drawScaledText(img *image.RGBA, text string, x, y, scale int, c color.Color) {
	if scale < 1 {
		scale = 1
	}
	const gw, gh = 7, 13
	w := len(text) * gw
	h := gh
	small := image.NewRGBA(image.Rect(0, 0, w, h))
	draw.Draw(small, small.Bounds(), image.NewUniform(color.White), image.Point{}, draw.Src)
	d := &font.Drawer{
		Dst:  small,
		Src:  image.NewUniform(color.Black),
		Face: basicfont.Face7x13,
		Dot:  fixed.P(0, gh-2),
	}
	d.DrawString(text)
	for sy := 0; sy < h; sy++ {
		for sx := 0; sx < w; sx++ {
			r, g, b, a := small.At(sx, sy).RGBA()
			if r < 0x8000 && g < 0x8000 && b < 0x8000 && a > 0 {
				draw.Draw(img, image.Rect(x+sx*scale, y+sy*scale, x+(sx+1)*scale, y+(sy+1)*scale), image.NewUniform(c), image.Point{}, draw.Src)
			}
		}
	}
}
